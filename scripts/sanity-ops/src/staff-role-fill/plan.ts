/**
 * Selection logic and the `apply.sh` text for the one-off `andere` fill (#3560).
 * Pure, so the dry run and the mutations file judge the same rows and a test
 * can pin the rule.
 *
 * `team.staff[].role` gained a third value, `andere`, so that an empty role
 * always means "nog niet ingevuld". Today's intentional empties — coordinators,
 * TVJO, verzorger, doorstroom and every other function that is neither trainer
 * nor delegate (#3420 Q9) — get `andere` once. An empty role on a trainer or
 * delegate title, or with no PSD title at all, stays empty: that one really is
 * "not done yet", and only the owner can say which bucket it belongs in.
 */

export interface TeamRow {
  _id: string;
  _rev: string;
  name: string | null;
  staff:
    | {
        _key: string;
        role?: string | null;
        member: {
          firstName: string | null;
          lastName: string | null;
          functionTitle: string | null;
        } | null;
      }[]
    | null;
}

export interface EmptyRoleEntry {
  docId: string;
  rev: string;
  team: string;
  key: string;
  name: string;
  functionTitle: string | null;
}

/** A PSD title that names a trainer (`T1`, `Keeperstrainer`, …) or a delegate. */
export function isTrainerOrDelegateTitle(title: string): boolean {
  return /^T\d|trainer|coach|afgevaardig|delegee/i.test(title);
}

/**
 * Every staff entry with an empty role, split into `andere` (the proposal)
 * and `undecided`. `add` / `skip` are staff `_key`s the owner moved by hand —
 * the key is the member's PSD id, so one key moves that person on every team.
 */
export function classifyEmptyRoles(
  rows: readonly TeamRow[],
  overrides: { add?: ReadonlySet<string>; skip?: ReadonlySet<string> } = {},
): { andere: EmptyRoleEntry[]; undecided: EmptyRoleEntry[] } {
  const andere: EmptyRoleEntry[] = [];
  const undecided: EmptyRoleEntry[] = [];
  for (const row of rows) {
    for (const s of row.staff ?? []) {
      if (s.role || !s.member) continue;
      const functionTitle = s.member.functionTitle?.trim() || null;
      const entry: EmptyRoleEntry = {
        docId: row._id,
        rev: row._rev,
        team: row.name ?? row._id,
        key: s._key,
        name: `${s.member.firstName ?? ""} ${s.member.lastName ?? ""}`.trim(),
        functionTitle,
      };
      const proposed =
        functionTitle !== null && !isTrainerOrDelegateTitle(functionTitle);
      const fill = overrides.add?.has(s._key)
        ? true
        : overrides.skip?.has(s._key)
          ? false
          : proposed;
      (fill ? andere : undecided).push(entry);
    }
  }
  return { andere, undecided };
}

/**
 * One patch per document, pinned to the revision read: a team an editor (or
 * the nightly sync) saved since fails the whole transaction instead of being
 * overwritten. Drafts are separate documents, so they get their own patch.
 */
export function buildMutations(entries: readonly EmptyRoleEntry[]) {
  const byDoc = new Map<string, { rev: string; set: Record<string, string> }>();
  for (const e of entries) {
    const doc = byDoc.get(e.docId) ?? { rev: e.rev, set: {} };
    doc.set[`staff[_key=="${e.key}"].role`] = "andere";
    byDoc.set(e.docId, doc);
  }
  return [...byDoc].map(([id, { rev, set }]) => ({
    patch: { id, ifRevisionID: rev, set },
  }));
}

/** Single-quote for bash: each `'` becomes `'\''` (close, escaped quote, reopen). */
const shellQuote = (s: string) => `'${s.replaceAll("'", "'\\''")}'`;

/** One transaction; the token never reaches argv or the output. */
export function applyScript(mutationsPath: string, dataset: string): string {
  return `#!/usr/bin/env bash
# Generated by scripts/sanity-ops/src/staff-role-fill (#3560). Sets
# team.staff[].role = "andere" in ONE transaction on dataset "${dataset}".
# Every patch is pinned to the revision read; a team saved since fails the
# whole transaction — re-run the script to rebuild this file.
set -euo pipefail
TOKEN="\${SANITY_API_TOKEN:-$(jq -r '.authToken // empty' "$HOME/.config/sanity/config.json")}"
[ -n "$TOKEN" ] || { echo "No Sanity token (SANITY_API_TOKEN or sanity login)." >&2; exit 1; }
printf 'Authorization: Bearer %s\\n' "$TOKEN" |
  curl -sS --fail-with-body -X POST \\
    -H @- -H 'Content-Type: application/json' \\
    --data-binary @${shellQuote(mutationsPath)} \\
    'https://vhb33jaz.api.sanity.io/v2024-01-01/data/mutate/${dataset}' |
  jq '{transactionId, results}'
`;
}
